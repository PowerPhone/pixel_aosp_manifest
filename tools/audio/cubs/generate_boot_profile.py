#!/usr/bin/env python3
"""Embed the qualified Cubs mono MCPS112 / two-slot ENTRY96 closure.

Build-time generation only. Exact region bytes are retained; no hashes or
device operations. The shared native factory transport is copied verbatim.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--capture', type=Path, default=ROOT / 'tools/audio/manifests/cubs_d10_native192_edge0_mcps112_control.json')
    parser.add_argument('--speaker', type=Path, default=ROOT / 'work/audio-research/cubs/direct192-two-slot-template-v5-window-frame-20260923/combined-manifest.json')
    parser.add_argument('--output-dir', type=Path, default=ROOT / 'tools/audio/device/cubs_powerphone_boot')
    args = parser.parse_args()
    capture = json.loads(args.capture.read_text())
    speaker = json.loads(args.speaker.read_text())
    if (capture['profile'] != 'cubs-15876290-polygon-exclusive-d10-native192-edge0-control'
            or capture.get('variant') != 'raw-mcps112-scheduling-control'
            or capture['geometry']['native_receiver_control_bit1'] != 0
            or capture['raw_mcps_vote_control'] != dict(raw_type=2, stock_mcps=28,
                 candidate_mcps=112, paired_enable_disable=True,
                 code_immediates_only=True, kernel_timeout_changed=False)):
        raise SystemExit('Require the exact mono edge0 / paired MCPS112 profile')
    geo = speaker['direct_playback']
    required = dict(pcm_device=5, sample_rate=192000, format='S32_LE', channels=2,
                    bclk_hz=12288000, slots=2, slot_bits=32, frames_per_half=96,
                    dma_half_bytes=768, ap_read_bytes=768, ring_sizes_changed=False)
    if any(geo.get(key) != value for key, value in required.items()):
        raise SystemExit('Require independently qualified D5 two-slot192 geometry')
    patches = capture['patches'] + speaker['patches']
    by_name = {entry['name']: entry for entry in patches}
    if len(by_name) != len(patches):
        raise SystemExit('Duplicate patch names')
    payload = bytes.fromhex(by_name['d5_payload']['after_hex'])
    if (int(by_name['d5_payload']['address'], 0) != 0x40274404
            or payload[4:8] != bytes(4) or payload[0x7c:0x7f] != bytes.fromhex('36c100')):
        raise SystemExit('Require zero boot-local pointer and worker ENTRY96')
    if bytes.fromhex(by_name['cache_wrapper']['after_hex'])[12:15] != bytes.fromhex('364100'):
        raise SystemExit('Cache wrapper must use ENTRY32')
    spans = sorted((int(p['address'], 0), len(bytes.fromhex(p['after_hex']))) for p in patches)
    if any(at + size > following for (at, size), (following, _) in zip(spans, spans[1:])):
        raise SystemExit('Overlapping profile regions')
    first = ['stage_gate', 'd5_payload', 'raw_mcps_enable_cave', 'raw_mcps_disable_cave']
    last = ['raw_mcps_enable_hook', 'raw_mcps_disable_hook', 'stream_rate']
    ordered = [by_name[name] for name in first]
    ordered += [p for p in patches if p['name'] not in first + last]
    ordered += [by_name[name] for name in last]
    lines = ['// Generated by tools/audio/cubs/generate_boot_profile.py; do not edit.',
             '#pragma once', '#include <cstdint>', 'namespace cubs_boot_profile {',
             'inline constexpr char kProfile[] = "mono192-edge0-mcps112-d5-two-slot-v5";',
             'struct Patch { const char* name; uint32_t address; const char* before; const char* after; };',
             'struct Guard { uint32_t address; const char* expected; };',
             'inline constexpr Patch kPatches[] = {']
    for p in ordered:
        before, after = bytes.fromhex(p['before_hex']), bytes.fromhex(p['after_hex'])
        if not before or len(before) != len(after):
            raise SystemExit('Invalid patch widths')
        lines.append(f'    {{"{p["name"]}", {p["address"]}, "{before.hex()}", "{after.hex()}"}},')
    lines += ['};', 'inline constexpr Guard kGuards[] = {']
    for guard in capture['guards'] + speaker['guards']:
        data = bytes.fromhex(guard['expected_hex'])
        lines.append(f'    {{{guard["address"]}, "{data.hex()}"}},')
    lines += ['};', '}  // namespace cubs_boot_profile', '']
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / 'profile_generated.h').write_text('\n'.join(lines))
    (args.output_dir / 'factory_transport.inc').write_bytes(
        (ROOT / 'tools/audio/device/frankel_aoc_diag/frankel_aoc_diag.cpp').read_bytes())
    print(f'Embedded {len(ordered)} patch regions and {len(capture["guards"]) + len(speaker["guards"])} guards in {args.output_dir}')


if __name__ == '__main__':
    main()
