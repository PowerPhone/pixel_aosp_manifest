/*
 * Batch ten native 192-frame mono Fullband blocks per RingBufferHost commit.
 *
 * CP2A.260805.005 produces one 0x300-byte S32 mono block per millisecond.
 * The whole-block profile commits each block independently.  This overlay
 * stages ten adjacent blocks and commits/notifies one fixed 0x1e00-byte batch,
 * reducing host traffic from 1000 to 100 commits per second without changing
 * the physical 192 kHz samples.
 *
 * The bytes are deliberately explicit: they are qualified for the RT500 F1
 * windowed ABI and are golden-compared by the host test.  In particular,
 * caller a10..a15 become callee a2..a7 across call8.
 */

    /* Per-open ordered reset.  Caller a14 -> callee a6 is object+0x800;
     * caller a15 -> callee a7 is proven zero at the hook.  Clear pending
     * count/base, order the stores, then publish active=1 at object+0x834. */
    .section .batch_start_reset,"ax"
    .align  1
    .global frankel_aoc_d12_batch10_start_reset
frankel_aoc_d12_batch10_start_reset:
    .byte   0x36,0x41,0x00, 0x79,0x56, 0x79,0x66, 0xc0,0x20,0x00
    .byte   0x0c,0x14, 0x42,0x46,0x34, 0x1d,0xf0, 0x00,0x00,0x00

    /* Replace the ordered stock active publication with call8 reset + a2=1. */
    .section .batch_start_hook,"ax"
    .align  1
    .global frankel_aoc_d12_batch10_start_hook
frankel_aoc_d12_batch10_start_hook:
    .byte   0x25,0xf7,0xb5, 0x22,0xa0,0x01

    /*
     * A: cache-clean fixed 0x1e00 bytes and tail-jump to B.  The entry at
     * +0x14 is an aligned inert callback used while live code is rewritten.
     */
    .section .batch_flush_and_inert,"ax"
    .align  4
    .global frankel_aoc_d12_batch10_flush
frankel_aoc_d12_batch10_flush:
    .byte   0x36,0x41,0x00, 0xad,0x03, 0x80,0xb5,0x11
    .byte   0x81,0xd3,0xe3, 0xe0,0x08,0x00, 0xc0,0x20,0x00
    .byte   0xc6,0x82,0x00
    .global frankel_aoc_d12_batch10_inert_callback
frankel_aoc_d12_batch10_inert_callback:
    .byte   0x36,0x41,0x00, 0x1d,0xf0, 0x00,0x00,0x00

    /*
     * B: output->vtable+0x18 AdvanceWritePointer(output,0x1e00), then pass
     * owner/base/output in outgoing a10/a11/a12 and call8 C.
     */
    .section .batch_advance_notify,"ax"
    .align  4
    .global frankel_aoc_d12_batch10_advance_notify
frankel_aoc_d12_batch10_advance_notify:
    .byte   0x68,0x04, 0x62,0x26,0x06, 0x80,0xb5,0x11
    .byte   0xad,0x04, 0xe0,0x06,0x00, 0xcd,0x04
    .byte   0xad,0x02, 0xbd,0x03, 0x25,0xa6,0x34, 0x1d,0xf0
    .byte   0x00,0x00,0x00,0x00

    /*
     * Replace the whole-block helper with its explicit movi-a3 aligned form at
     * the start of the 51-byte cave.  C begins at +0x1b and constructs 0x1e00
     * itself; it never trusts mutable output+0xc0 for a fixed ten-block batch.
     */
    .section .batch_no_sync_and_notify,"ax"
    .align  1
    .byte   0x00,0x00,0x00
    .global frankel_aoc_d12_no_sync_wholeblock_mono_aligned
frankel_aoc_d12_no_sync_wholeblock_mono_aligned:
    .byte   0x36,0x41,0x00, 0x42,0x03,0x00
    .byte   0x40,0x40,0x24, 0x66,0x14,0x09, 0x5d,0x02
    .byte   0x62,0xd5,0x08, 0x0c,0x33, 0xc6,0xe4,0xc8, 0x1d,0xf0
    .global frankel_aoc_d12_batch10_notify
frankel_aoc_d12_batch10_notify:
    .byte   0x36,0x41,0x00, 0xa2,0x22,0x77, 0xbd,0x03
    .byte   0x1c,0xec, 0x80,0xcc,0x11, 0x0c,0x1e, 0x0c,0x0f
    .byte   0xa5,0xe8,0x8e, 0x1d,0xf0, 0x00,0x00

    /*
     * Replace only the stock output memcpy/cache/commit/notify tail.
     * GetWritePointer is called once at count zero.  A NULL return branches
     * to the stock statistics continuation without copying or incrementing.
     * On count ten, A/B/C commit exactly 0x1e00 bytes.  a3 is restored from
     * a6 before returning to the untouched code at 0x403e88d4.
     */
    .section .batch_output_tail,"ax"
    .align  1
    .global frankel_aoc_d12_batch10_output_tail
frankel_aoc_d12_batch10_output_tail:
    .byte   0x56,0x62,0x00, 0x29,0x56, 0x29,0x66, 0x86,0x15,0x00
    .byte   0x78,0x56, 0xdc,0x07, 0xa2,0x25,0x50, 0x48,0x0a
    .byte   0x42,0x24,0x17, 0xe0,0x04,0x00, 0x2d,0x0a, 0x29,0x66
    .byte   0x16,0x12,0x03              /* beqz a2,0x403e88d1 */
    .byte   0x28,0x66, 0x70,0x47,0x90, 0x80,0x44,0x11, 0x40,0xa2,0x80
    .byte   0x42,0xa2,0x1c,0x40, 0xb5,0x80, 0xc2,0xa3,0x00
    .byte   0x81,0xa3,0x22, 0xe0,0x08,0x00, 0x1b,0x77, 0x79,0x56
    .byte   0x66,0x97,0x10, 0x70,0xd7,0x90 /* a13=3*count=30 */
    .byte   0x0c,0x07, 0x79,0x56, 0xad,0x05, 0xbd,0x02
    .byte   0xc2,0x25,0x50, 0x65,0xf4,0xd8, 0x60,0x36,0x20
